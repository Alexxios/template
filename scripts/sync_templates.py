"""Register src/ templates, generate validation workflows, and refresh README badges."""

from __future__ import annotations

import argparse
import keyword
import re
import tomllib
from pathlib import Path

from jinja2 import Environment, FileSystemLoader, StrictUndefined, TemplateError

ROOT = Path(__file__).resolve().parents[1]
BEGIN = "<!-- BEGIN GENERATED TEMPLATE STATUS -->"
END = "<!-- END GENERATED TEMPLATE STATUS -->"
GENERATED = "# Generated by scripts/sync_templates.py;"
NAME = re.compile(r"[a-z][a-z0-9]*(?:[-_][a-z0-9]+)*")
SHARED_VALIDATION_PATHS = [
    "tests/__init__.py",
    "tests/support.py",
    "scripts/sync_templates.py",
    "pyproject.toml",
    "uv.lock",
    ".python-version",
]


def package_name(name: str) -> str:
    package = name.replace("-", "_")
    if not NAME.fullmatch(name) or keyword.iskeyword(package):
        raise ValueError(f"Invalid template name: {name!r}")
    return package


def update_readme(readme: str, status: str) -> str:
    """Replace only the managed header, leaving hand-written content intact."""
    if BEGIN in readme and END in readme:
        before, rest = readme.split(BEGIN, 1)
        _, after = rest.split(END, 1)
        return before + status.rstrip() + after
    if BEGIN in readme or END in readme:
        raise ValueError("README has an incomplete generated-status section")
    title, _, body = readme.partition("\n")
    return title + "\n\n" + status + "\n" + body.lstrip("\n")


def planned_files(root: Path) -> dict[Path, str | None]:
    environment = Environment(
        loader=FileSystemLoader(root / "templates/validation"),
        undefined=StrictUndefined,
        variable_start_string="[[",
        variable_end_string="]]",
        keep_trailing_newline=True,
        trim_blocks=True,
        lstrip_blocks=True,
    )
    repository = tomllib.loads((root / "pyproject.toml").read_text())["tool"]["template_ci"][
        "repository"
    ]
    if not re.fullmatch(r"[\w.-]+/[\w.-]+", repository):
        raise ValueError("tool.template_ci.repository must be a GitHub owner/repository")
    files: dict[Path, str | None] = {}
    templates = []
    packages = set()
    for source in sorted((root / "src").glob("*/cookiecutter.json")):
        name = source.parent.name
        package = package_name(name)
        if package in packages:
            raise ValueError(f"Templates share the tests/{package} package")
        packages.add(package)
        module = root / "tests" / f"{package}.py"
        if module.exists():
            raise FileExistsError(f"Template conflicts with existing test module: {module}")
        directory = root / "tests" / package
        config_path = directory / "validation.toml"
        if not config_path.is_file():
            if directory.exists():
                raise FileExistsError(f"Refusing to overwrite existing test package: {directory}")
            for seed in sorted((root / "templates/validation/package").glob("*.jinja")):
                files[directory / seed.stem] = environment.get_template(
                    f"package/{seed.name}"
                ).render(template=name)
        config = tomllib.loads(files.get(config_path) or config_path.read_text())
        if config["template"] != name:
            raise ValueError(f"{config_path} must declare template = {name!r}")
        for required in ("__init__.py", "__main__.py", "scaffold.py"):
            if directory / required not in files and not (directory / required).is_file():
                raise FileNotFoundError(directory / required)
        workflow = f"validate-{name}.yml"
        paths = [f"src/{name}/**", f"tests/{package}/**", *SHARED_VALIDATION_PATHS]
        item = {
            **config,
            "package": package,
            "github_paths": [
                *paths,
                "templates/validation/github.yml.jinja",
                f".github/workflows/{workflow}",
            ],
            # Watching the combined generated Sourcecraft file would run every
            # template whenever one template's validation settings change.
            "sourcecraft_paths": [
                *paths,
                "templates/validation/sourcecraft.yaml.jinja",
                "scripts/sourcecraft_repo.py",
            ],
        }
        url = f"https://github.com/{repository}/actions/workflows/{workflow}"
        item.update(link=f"[{name}](src/{name}/)", badge=f"[![{name}]({url}/badge.svg)]({url})")
        templates.append(item)
        path = root / ".github/workflows" / workflow
        if path.exists() and not path.read_text().startswith(GENERATED):
            raise FileExistsError(f"Refusing to overwrite a hand-written workflow: {path}")
        files[path] = environment.get_template("github.yml.jinja").render(**item).rstrip() + "\n"

    pages = root / ".github/workflows/pages.yml"
    if pages.exists() and not pages.read_text().startswith(GENERATED):
        raise FileExistsError(f"Refusing to overwrite a hand-written workflow: {pages}")
    files[pages] = (
        environment.get_template("pages.yml.jinja").render(templates=templates).rstrip() + "\n"
    )

    # Only obsolete workflows carrying our marker may be removed.
    for path in (root / ".github/workflows").glob("validate-*.yml"):
        if path not in files and path.read_text().startswith(GENERATED):
            files[path] = None
    files[root / ".sourcecraft/ci.yaml"] = (
        environment.get_template("sourcecraft.yaml.jinja")
        .render(templates=[item for item in templates if "sourcecraft" in item])
        .rstrip()
        + "\n"
    )
    status = environment.get_template("readme.md.jinja").render(templates=templates)
    readme = root / "README.md"
    files[readme] = update_readme(readme.read_text(), status)
    return files


def sync(root: Path = ROOT, *, check: bool = False) -> list[Path]:
    """Keep custom fixture packages intact; regenerate their workflow definitions."""
    planned = planned_files(root)
    changed = {
        path: content
        for path, content in planned.items()
        if (path.read_text() if path.exists() else None) != content
    }
    if not check:
        originals = {path: path.read_text() if path.exists() else None for path in changed}
        new_directories = set()
        for path in changed:
            for parent in path.parents:
                if parent.exists():
                    break
                new_directories.add(parent)
        try:
            for path, content in changed.items():
                if content is None:
                    path.unlink()
                else:
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_text(content)
        except OSError:
            for path, content in originals.items():
                if content is None:
                    path.unlink(missing_ok=True)
                else:
                    path.write_text(content)
            for directory in sorted(
                new_directories, key=lambda path: len(path.parts), reverse=True
            ):
                if directory.exists() and not any(directory.iterdir()):
                    directory.rmdir()
            raise
    return list(changed)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Fail on drift without modifying files"
    )
    args = parser.parse_args()
    try:
        changed = sync(check=args.check)
    except (OSError, ValueError, KeyError, TemplateError) as exc:
        parser.exit(1, f"ERROR: {exc}\n")
    for path in changed:
        print(f"{'Out of date' if args.check else 'Updated'}: {path.relative_to(ROOT)}")
    if args.check and changed:
        parser.exit(
            1, "Run uv run python scripts/sync_templates.py and commit the generated files.\n"
        )


if __name__ == "__main__":
    main()
